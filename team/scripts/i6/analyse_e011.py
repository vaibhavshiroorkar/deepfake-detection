"""E-011 analysis: in-domain visual and audio heads on LAV-DF, pre-check and late fusion (D-058).

    PYTHONPATH=src .venv/Scripts/python.exe scripts/i6/analyse_e011.py [--write]

Inputs: data/_results/I-6/visual_lavdf_s{0,1,2}.npz (scripts/i6/train_visual_lavdf.py) and audio_lavdf.npz (scripts/i6/train_audio_lavdf.py).
Calibration: a temperature per modality and seed fitted on the fusion-fit subset `train` (never seen by the heads). Fusion rules and the verdict
lines as in E-010: sum of calibrated log-odds; logistic regression fitted on the fusion-fit subset against the fused label.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

import analyse_i6 as A6
from dfd.eval import bootstrap as B
from dfd.eval import calibration as C
from dfd.eval import metrics as M

OUT = Path("data/_results/I-6")
MARK_B, MARK_E = "<!-- E-011 RESULT begin (generated by scripts/i6/analyse_e011.py) -->", "<!-- E-011 RESULT end -->"
fmt, dfmt, logit = A6.fmt, A6.dfmt, A6.logit


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    meta = {s: np.load(OUT / f"scores_{s}.npz", allow_pickle=True) for s in ("train", "val")}      # labels, groups and cells of the E-010 subset
    vis = {s: [np.load(OUT / f"visual_lavdf_s{k}.npz", allow_pickle=True) for k in range(3)] for s in ("train", "val")}
    aud = np.load(OUT / "audio_lavdf.npz", allow_pickle=True)
    for s in ("train", "val"):
        assert all(np.array_equal(v[f"{s}_sample_id"], meta[s]["sample_id"]) for v in vis[s]) and np.array_equal(aud[f"{s}_sample_id"], meta[s]["sample_id"])
    pv = {s: np.array([v[f"{s}_p"] for v in vis[s]]) for s in ("train", "val")}        # [3, N]
    pa = {s: aud[f"{s}_p"] for s in ("train", "val")}                                     # [members, 3, N]
    ytr, yva = meta["train"], meta["val"]
    # temperatures on the fusion-fit subset
    Tv, Ta = [], []
    for k in range(3):
        ok = ~np.isnan(pv["train"][k])
        Tv.append(C.fit_temperature(logit(pv["train"][k][ok]), ytr["y_video"][ok]).temperature)
        Ta.append(C.fit_temperature(np.mean([logit(pa["train"][m, k]) for m in range(3)], axis=0), ytr["y_audio"]).temperature)

    def lv(s):
        return np.nanmean([logit(pv[s][k]) / Tv[k] for k in range(3)], axis=0)

    def la(s):
        return np.mean([np.mean([logit(pa[s][m, k]) for m in range(3)], axis=0) / Ta[k] for k in range(3)], axis=0)
    vt, at, vv, av = lv("train"), la("train"), lv("val"), la("val")
    g, yf, yv, ya = yva["group"], yva["y_fused"], yva["y_video"], yva["y_audio"]
    ok = ~np.isnan(vv)

    def auc(y, s, m=None):
        m = np.ones(len(y), bool) if m is None else m
        return B.cluster_bootstrap(y[m], s[m], g[m], "auc", n_boot=B.N_BOOT).as_dict()
    res = dict(date=time.strftime("%Y-%m-%d %H:%M"), T_visual=Tv, T_audio=Ta, no_face=dict(train=int(np.isnan(vt).sum()), val=int((~ok).sum())))
    pre = dict(visual_vs_video=auc(yv, vv, ok), audio_vs_audio=auc(ya, av), visual_vs_fused=auc(yf, vv, ok), audio_vs_fused=auc(yf, av),
               visual_vs_audio_label=auc(ya, vv, ok), audio_vs_video_label=auc(yv, av))
    res["precheck"] = pre
    res["visual_pass"], res["audio_pass"] = bool(pre["visual_vs_video"]["low"] > 0.55), bool(pre["audio_vs_audio"]["low"] > 0.55)
    cells = {}
    for cell in ("video_fake", "audio_fake", "both_fake"):
        m = (yva["cell"] == cell) | (yva["cell"] == "real")
        cells[cell] = dict(visual=auc((yva["cell"] == cell).astype(int), vv, m & ok), audio=auc((yva["cell"] == cell).astype(int), av, m))
    res["per_cell"] = cells
    res["ece"] = dict(visual=M.ece(yv[ok], 1 / (1 + np.exp(-vv[ok]))), audio=M.ece(ya, 1 / (1 + np.exp(-av))))
    res["corr_logits"] = dict(real=float(np.corrcoef(vv[ok & (yf == 0)], av[ok & (yf == 0)])[0, 1]), fake=float(np.corrcoef(vv[ok & (yf == 1)], av[ok & (yf == 1)])[0, 1]))
    w = A6.fit_lr(np.c_[np.nan_to_num(vt), at], ytr["y_fused"])
    vv0 = np.nan_to_num(vv)
    rules = {"sum of log-odds": vv0 + av, "logistic regression": w[0] + w[1] * vv0 + w[2] * av}
    single = {"visual head": vv0, "audio head": av}
    sauc = {k: auc(yf, v) for k, v in single.items()}
    fus = {k: auc(yf, v) for k, v in rules.items()}
    best_single, best_rule = max(sauc, key=lambda k: sauc[k]["estimate"]), max(fus, key=lambda k: fus[k]["estimate"])
    d, _, _ = B.paired_bootstrap(yf, rules[best_rule], single[best_single], g, "auc", n_boot=B.N_BOOT)
    res.update(single_fused_label=sauc, fusion_fused_label=fus, best_single=best_single, best_rule=best_rule, diff=d.as_dict(),
               lr_weights=dict(w0=float(w[0]), w_visual=float(w[1]), w_audio=float(w[2])))
    res["fusion_other_labels"] = {k: dict(video=auc(yv, v), audio=auc(ya, v)) for k, v in {**rules, **single}.items()}
    c1, c2, c3 = res["visual_pass"], res["audio_pass"], bool(d.low > 0)
    res["criteria"] = dict(C1_visual_pass=c1, C2_audio_pass=c2, C3_fusion_gain=c3)
    if c1 and c2 and c3:
        verdict = "SUPPORTED"
    elif c1 and c2:
        verdict = "PARTIAL (both in-domain heads pass the pre-check; the fusion interval includes zero or is below zero)"
    elif c1 or c2:
        verdict = "PARTIAL (only the " + ("visual" if c1 else "audio") + " in-domain head passes the pre-check; no fused result is claimed)"
    else:
        verdict = "NOT SUPPORTED (neither in-domain head passes the pre-check)"
    res["verdict"] = verdict
    md = [f"Temperatures fitted on the fusion-fit subset (seeds 0, 1, 2): visual {np.round(Tv, 3).tolist()}, audio {np.round(Ta, 3).tolist()}. Clips without a visual score: train {res['no_face']['train']}, val {res['no_face']['val']} of 2,000.", "",
          "Pre-check on LAV-DF val (in-domain heads; AUC [95% group bootstrap]; E-010 values of the frozen out-of-domain heads in the last column):", "",
          "| head | against its own modality label | against the fused label | against the other modality's label | E-010 frozen head, own label |", "|---|---|---|---|---|",
          f"| visual (IMG-17 fine-tuned on LAV-DF) | {fmt(pre['visual_vs_video'])} | {fmt(pre['visual_vs_fused'])} | {fmt(pre['visual_vs_audio_label'])} | 0.3838 [0.3599, 0.4079] |",
          f"| audio (AU-8 + AU-4 + AU-6 on LAV-DF) | {fmt(pre['audio_vs_audio'])} | {fmt(pre['audio_vs_fused'])} | {fmt(pre['audio_vs_video_label'])} | 0.6476 [0.6244, 0.6701] |", "",
          f"Pre-check rule: lower bound above 0.55. Visual: {'pass' if c1 else 'FAIL'}; audio: {'pass' if c2 else 'FAIL'}.", "",
          "Per cell on val (the cell against the real videos), AUC [95%]:", "", "| cell | visual head | audio head |", "|---|---|---|"]
    md += [f"| {c} | {fmt(v['visual'])} | {fmt(v['audio'])} |" for c, v in cells.items()]
    md += ["", f"ECE on val against the own modality label (temperature from the fusion-fit subset): visual {res['ece']['visual']:.4f}, audio {res['ece']['audio']:.4f}. Pearson correlation of the calibrated log-odds on val: real clips {res['corr_logits']['real']:.3f}, fake clips {res['corr_logits']['fake']:.3f}.", "",
           f"Fusion on val. Logistic regression fitted on the fusion-fit subset: intercept {w[0]:+.3f}, visual weight {w[1]:.3f}, audio weight {w[2]:.3f}.", "",
           "| scores | AUC [95%] fused label | AUC against modify_video | AUC against modify_audio |", "|---|---|---|---|"]
    for k in list(single) + list(rules):
        row = sauc[k] if k in single else fus[k]
        o = res["fusion_other_labels"][k]
        md.append(f"| {k} | {fmt(row)} | {fmt(o['video'])} | {fmt(o['audio'])} |")
    md += ["", f"Best single head by val AUC: {best_single}; best fusion rule by val AUC: {best_rule}; difference (best rule minus best single head, paired group bootstrap): {dfmt(res['diff'])}.",
           f"Criteria: C1 visual pass {c1}, C2 audio pass {c2}, C3 fusion lower bound above 0 {c3}.", "", f"**VERDICT (mechanical, exploratory, D-041): {verdict}.**"]
    block = "\n".join(md)
    (OUT / "e011.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "e011.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/i6/analyse_e011.py from data/_results/I-6, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-011)" in t
            t = t.replace("- Result: (written by script after the run, E-011)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
