"""E-012 analysis: visual head trained on produced videos only (D-059). AUC only; no calibration is needed.

    PYTHONPATH="src;scripts/i6" .venv/Scripts/python.exe scripts/i6/analyse_e012.py [--write]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

import analyse_i6 as A6
from dfd.eval import bootstrap as B

OUT = Path("data/_results/I-6")
MARK_B, MARK_E = "<!-- E-012 RESULT begin (generated by scripts/i6/analyse_e012.py) -->", "<!-- E-012 RESULT end -->"
fmt, dfmt, logit = A6.fmt, A6.dfmt, A6.logit


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    v = np.load(OUT / "scores_val.npz", allow_pickle=True)
    new = np.array([logit(np.load(OUT / f"visual_lavdf_produced_s{k}.npz", allow_pickle=True)["val_p"]) for k in range(3)])
    old = np.array([logit(np.load(OUT / f"visual_lavdf_s{k}.npz", allow_pickle=True)["val_p"]) for k in range(3)])
    g, cell = v["group"], v["cell"]
    prod = cell != "real"

    def auc(y, s, m):
        return B.cluster_bootstrap(y[m], s[:, m] if s.ndim == 2 else s[m], g[m], "auc", n_boot=B.N_BOOT).as_dict()
    res = dict(within_produced_new=auc(v["y_video"], new, prod), within_produced_old=auc(v["y_video"], old, prod),
               all_new=auc(v["y_video"], new, np.ones(len(g), bool)), all_old=auc(v["y_video"], old, np.ones(len(g), bool)),
               fused_new=auc(v["y_fused"], new, np.ones(len(g), bool)),
               real_vs_audio_only_new=auc((cell == "audio_fake").astype(int), new, (cell == "real") | (cell == "audio_fake")),
               real_vs_video_fake_new=auc((cell == "video_fake").astype(int), new, (cell == "real") | (cell == "video_fake")))
    d, _, _ = B.paired_bootstrap(v["y_video"][prod], new[:, prod], old[:, prod], g[prod], "auc", n_boot=B.N_BOOT)
    res["diff_within_produced"] = d.as_dict()
    res["cells_within_produced"] = {c: auc((cell == c).astype(int), new, (cell == c) | (cell == "audio_fake")) for c in ("video_fake", "both_fake")}
    ok = res["within_produced_new"]["low"] > 0.55 and d.low > 0
    res["verdict"] = "SUPPORTED" if ok else "NOT SUPPORTED (the within-produced lower bound is at or below 0.55, or the difference to the E-011 head includes zero)"
    md = ["AUC [95% group bootstrap] on LAV-DF val, seeds averaged. Within produced = cells video_fake, both_fake (positives) and audio_fake (negatives); the head of E-011 is scored on the same clips.", "",
          "| quantity | E-012 head (produced only) | E-011 head (all videos) |", "|---|---|---|",
          f"| within produced videos, against modify_video | {fmt(res['within_produced_new'])} | {fmt(res['within_produced_old'])} |",
          f"| all val videos, against modify_video | {fmt(res['all_new'])} | {fmt(res['all_old'])} |", "",
          f"Difference within produced videos (E-012 minus E-011, paired group bootstrap): {dfmt(res['diff_within_produced'])}.",
          f"E-012 head, fused label over all videos: {fmt(res['fused_new'])}. Real originals against audio-only fakes (video unmodified): {fmt(res['real_vs_audio_only_new'])}; against video-only fakes: {fmt(res['real_vs_video_fake_new'])}.",
          "Within produced videos, per fake cell against audio-only fakes: " + "; ".join(f"{c} {fmt(r)}" for c, r in res["cells_within_produced"].items()) + ".", "",
          f"**VERDICT (mechanical, exploratory, D-041): {res['verdict']}.**"]
    block = "\n".join(md)
    (OUT / "e012.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "e012.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/i6/analyse_e012.py from data/_results/I-6, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-012)" in t
            t = t.replace("- Result: (written by script after the run, E-012)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
