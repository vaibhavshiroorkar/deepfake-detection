"""E-008 (hypothesis H-A2 of D-055): nuisance augmentation of the speech training clips.

    # 1. features (GPU, CPU workers): see the Command line of E-008 in docs/EXPERIMENTS.md
    # 2. heads, precondition check, paired comparison with the E-007 head (CPU):
    PYTHONPATH=src .venv/Scripts/python.exe scripts/i3/run_ha2.py [--write]

Heads: the recipe of dfd.sweep.heads (seeds 0, 1, 2). Baseline: the E-007 head, retrained here on the same features and seeds (its AUCs are
checked against data/_results/I-2/ha1.json). New head: trained on the E-007 features plus the three augmented copies of every training clip
(rows of one clip share the clip index), early stopping on the clean validation split. Paired group bootstrap (speaker), 2,000 resamples.
Output data/_results/I-3/ha2.json and ha2.md; with --write the "Result" line of E-008 in docs/EXPERIMENTS.md is replaced between markers.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from dfd.eval import bootstrap as B
from dfd.eval import calibration as C
from dfd.eval import metrics as M
from dfd.sweep import heads, rank, tasks

OUT = Path("data/_results/I-3")
FEATS = Path("data/_features_trimnorm")
AUG = Path("data/_features_aug/AU-8/T-A")
I0 = Path("data/_results/I-0/T-A/scores.npz")
HA1 = Path("data/_results/I-2/ha1.json")
MARK_B, MARK_E = "<!-- E-008 RESULT begin (generated by scripts/i3/run_ha2.py) -->", "<!-- E-008 RESULT end -->"


def fmt(b):
    return f"{b['estimate']:.4f} [{b['low']:.4f}, {b['high']:.4f}]"


def load_aug(name, sample_id):
    z = np.load(AUG / f"{name}.npz", allow_pickle=False)
    assert np.array_equal(z["sample_id"].astype(str), sample_id), f"{name}: item order differs from the E-007 features"
    return z["feats"].astype(np.float32)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    tasks.FEATURES = FEATS
    task = tasks.TASKS["T-A"]
    tr, _ = rank.load_split("AU-8", task, task.train)
    va, _ = rank.load_split("AU-8", task, task.val)
    dv, _ = rank.load_split("AU-8", task, task.devx)
    n = tr.y.size
    Xa = [load_aug(f"asvspoof_train_aug{k}", tr.sample_id) for k in (1, 2, 3)]
    tr_aug = heads.Split(np.concatenate([tr.X] + Xa), np.concatenate([tr.clip_of] + [np.arange(n)] * 3), tr.y, tr.groups, tr.sample_id)
    va_aug = heads.Split(load_aug("asvspoof_dev_aug1", va.sample_id), va.clip_of, va.y, va.groups, va.sample_id)
    t0 = time.time()
    base = [heads.train_head(tr, va, s) for s in (0, 1, 2)]
    new = [heads.train_head(tr_aug, va, s) for s in (0, 1, 2)]

    def sc(hs, sp):
        return np.array([heads.clip_scores(h.prob_rows(sp.X), sp.clip_of, sp.y.size) for h in hs])
    S = {"base": {"val": sc(base, va), "dev": sc(base, dv), "val_aug": sc(base, va_aug)},
         "new": {"val": sc(new, va), "dev": sc(new, dv), "val_aug": sc(new, va_aug)}}
    z0 = np.load(I0, allow_pickle=True)
    assert np.array_equal(z0["val_sample_id"], va.sample_id) and np.array_equal(z0["dev_sample_id"], dv.sample_id)
    res = dict(date=time.strftime("%Y-%m-%d %H:%M"), seconds=round(time.time() - t0), best_epochs=dict(base=[h.best_epoch for h in base], new=[h.best_epoch for h in new]),
               rows=dict(base=int(tr.X.shape[0]), new=int(tr_aug.X.shape[0])))
    for name, sp, key, old0 in (("validation", va, "val", z0["val_scores"]), ("dev_x", dv, "dev", z0["dev_scores"])):
        d, bn, bo = B.paired_bootstrap(sp.y, S["new"][key], S["base"][key], sp.groups, "auc", n_boot=B.N_BOOT)
        d0, _, bz = B.paired_bootstrap(sp.y, S["new"][key], old0, sp.groups, "auc", n_boot=B.N_BOOT)
        res[name] = dict(new=bn.as_dict(), base=bo.as_dict(), i0=bz.as_dict(), diff_vs_base=d.as_dict(), diff_vs_i0=d0.as_dict())
    # E-007 reproduction check
    h1 = json.loads(Path("data/_results/I-2/ha1.json").read_text())
    res["e007_reproduced"] = dict(val=[res["validation"]["base"]["estimate"], h1["validation"]["new"]["estimate"]], dev=[res["dev_x"]["base"]["estimate"], h1["dev_x"]["new"]["estimate"]])
    # robustness: AUC on the clean and on the augmented validation copy
    rob = {}
    for who in ("base", "new"):
        rob[who] = dict(clean=B.cluster_bootstrap(va.y, S[who]["val"], va.groups, "auc", n_boot=B.N_BOOT).as_dict(),
                        aug=B.cluster_bootstrap(va.y, S[who]["val_aug"], va.groups, "auc", n_boot=B.N_BOOT).as_dict())
    res["robustness"] = rob
    drop_base = rob["base"]["clean"]["estimate"] - rob["base"]["aug"]["estimate"]
    drop_new = rob["new"]["clean"]["estimate"] - rob["new"]["aug"]["estimate"]
    res["perturbation_drop"] = dict(base=drop_base, new=drop_new)
    res["precondition_ok"] = bool(drop_base >= 0.01)
    # calibration (temperature fitted on clean validation, seed-wise)
    ece = {"validation": [], "dev_x": []}
    for i in range(3):
        T = C.fit_temperature(C.logit(S["new"]["val"][i]), va.y).temperature
        ece["validation"].append((M.ece(va.y, S["new"]["val"][i]), M.ece(va.y, C.sigmoid(C.logit(S["new"]["val"][i]) / T))))
        ece["dev_x"].append((M.ece(dv.y, S["new"]["dev"][i]), M.ece(dv.y, C.sigmoid(C.logit(S["new"]["dev"][i]) / T))))
    res["ece_before_after"] = {k: np.mean(v, axis=0).tolist() for k, v in ece.items()}
    d_dev, d_val = res["dev_x"]["diff_vs_base"], res["validation"]["diff_vs_base"]
    if not res["precondition_ok"]:
        verdict = "NOT TESTED (the augmentation lowers the E-007 head AUC on the augmented validation copy by less than 0.01)"
    elif d_dev["low"] > 0 and d_val["estimate"] >= -0.02:
        verdict = "SUPPORTED"
    else:
        verdict = "NOT SUPPORTED (dev_x paired interval includes zero or is below zero, or validation AUC fell by more than 0.02)"
    res["verdict"] = verdict
    md = ["| split | new (augmented training) | E-007 head | I-0 probe | new minus E-007 | new minus I-0 |", "|---|---|---|---|---|---|"]
    for name in ("validation", "dev_x"):
        o = res[name]
        md.append(f"| {name} | {fmt(o['new'])} | {fmt(o['base'])} | {fmt(o['i0'])} | {o['diff_vs_base']['estimate']:+.4f} [{o['diff_vs_base']['low']:+.4f}, {o['diff_vs_base']['high']:+.4f}] | {o['diff_vs_i0']['estimate']:+.4f} [{o['diff_vs_i0']['low']:+.4f}, {o['diff_vs_i0']['high']:+.4f}] |")
    md += ["", "Robustness on ASVspoof dev, clean against one augmented copy (copy 1), AUC [95% interval]:", "", "| head | clean | augmented copy | drop |", "|---|---|---|---|"]
    md.append(f"| E-007 head | {fmt(rob['base']['clean'])} | {fmt(rob['base']['aug'])} | {drop_base:+.4f} |")
    md.append(f"| new head | {fmt(rob['new']['clean'])} | {fmt(rob['new']['aug'])} | {drop_new:+.4f} |")
    md += ["", f"Training rows: E-007 head {res['rows']['base']}, new head {res['rows']['new']}. Early-stopping epochs (seeds 0, 1, 2): E-007 head {res['best_epochs']['base']}, new head {res['best_epochs']['new']}. "
           f"The retrained E-007 head gives validation {res['e007_reproduced']['val'][0]:.4f} and dev_x {res['e007_reproduced']['dev'][0]:.4f} against {res['e007_reproduced']['val'][1]:.4f} and {res['e007_reproduced']['dev'][1]:.4f} logged in E-007.",
           "", f"ECE before / after temperature scaling (fitted on clean validation), new head: validation {res['ece_before_after']['validation'][0]:.4f} / {res['ece_before_after']['validation'][1]:.4f}, dev_x {res['ece_before_after']['dev_x'][0]:.4f} / {res['ece_before_after']['dev_x'][1]:.4f} (E-007 head: 0.0835 / 0.0048 and 0.2252 / 0.3116).",
           "", f"Precondition {'passed' if res['precondition_ok'] else 'FAILED'} (the E-007 head loses {drop_base:+.4f} AUC on the augmented validation copy; required at least 0.01)."]
    gain = d_dev["estimate"]
    md.append(f"Prediction check: dev_x gain +0.03 to +0.12 over the E-007 head, found {gain:+.4f} ({'inside' if 0.03 <= gain <= 0.12 else 'larger than' if gain > 0.12 else 'smaller than'} the range); validation change at most -0.01, found {d_val['estimate']:+.4f}; the new head loses {drop_new:+.4f} on the augmented copy against {drop_base:+.4f} for the E-007 head.")
    md += ["", f"**VERDICT (mechanical, exploratory on dev_x, D-041): {verdict}.**"]
    block = "\n".join(md)
    (OUT / "ha2.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "ha2.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/i3/run_ha2.py from data/_results/I-3, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-008)" in t
            t = t.replace("- Result: (written by script after the run, E-008)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
