"""E-007 (hypothesis H-A1 of D-051): speech preprocessing that removes leading and trailing silence and peak-normalises each clip.

    # 1. features (GPU, after the I-1 runs):
    PYTHONPATH=src .venv/Scripts/python.exe -m dfd.sweep.extract_audio --cand AU-8 --variant trim_norm --out-root data/_features_trimnorm
    # 2. heads, manipulation check, paired comparison with the I-0 probe (CPU):
    PYTHONPATH=src .venv/Scripts/python.exe scripts/i2/run_ha1.py [--write]

Reads ASVspoof 2019 LA train and dev and In-the-Wild dev_x only. Heads: the recipe of dfd.sweep.heads (seeds 0, 1, 2). Comparison: AU-8 probe of
I-0 (data/_results/I-0/T-A/scores.npz), paired group bootstrap (speaker), 2,000 resamples. Manipulation check: the four trivial features of M-004
recomputed on the preprocessed signal (leading silence and RMS of the 4 s window; duration and repeat-padded fraction of the trimmed clip).
Output data/_results/I-2/ha1.json and ha1.md; with --write the "Result" line of E-007 in docs/EXPERIMENTS.md is replaced between markers.
"""
from __future__ import annotations

import argparse
import json
import multiprocessing as mp
from pathlib import Path

import numpy as np

from dfd.data import loaders as L
from dfd.eval import bootstrap as B
from dfd.eval import calibration as C
from dfd.eval import metrics as M
from dfd.eval.threshold import choose_threshold_max_balanced_accuracy as thr_fn
from dfd.prep import audio as A
from dfd.sweep import extract_audio, heads, rank, tasks

OUT = Path("data/_results/I-2")
FEATS = Path("data/_features_trimnorm")
I0 = Path("data/_results/I-0/T-A/scores.npz")
SR, WIN = 16000, A.WINDOW_SAMPLES
MARK_B, MARK_E = "<!-- E-007 RESULT begin (generated by scripts/i2/run_ha1.py) -->", "<!-- E-007 RESULT end -->"
NAMES = ["leading_silence_s", "duration_s", "rms", "repeat_pad_fraction"]


def feats_of(path):
    wav = A.load_audio(path)
    tr = A.trim_and_peak_normalise(wav)
    win = A.window_first_repeat(tr)
    loud = np.nonzero(np.abs(win) > A.SILENCE_THRESHOLD)[0]
    return ((loud[0] if loud.size else win.size) / SR, tr.size / SR, float(np.sqrt(np.mean(win ** 2))), max(0.0, 1.0 - tr.size / WIN))


def ci(b):
    return f"{b.estimate:.4f} [{b.low:.4f}, {b.high:.4f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    tasks.FEATURES = FEATS            # the feature files of the variant; feature_path reads this module attribute
    task = tasks.TASKS["T-A"]
    tr, _ = rank.load_split("AU-8", task, task.train)
    va, vmeta = rank.load_split("AU-8", task, task.val)
    dv, _ = rank.load_split("AU-8", task, task.devx)
    assert "trim" in vmeta["preprocessing"], "the feature files are not the trim_norm variant"
    hs = [heads.train_head(tr, va, s) for s in (0, 1, 2)]
    S = {k: np.array([heads.clip_scores(h.prob_rows(sp.X), sp.clip_of, sp.y.size) for h in hs]) for k, sp in (("val", va), ("dev", dv))}
    z0 = np.load(I0, allow_pickle=True)
    assert np.array_equal(z0["val_sample_id"], va.sample_id) and np.array_equal(z0["dev_sample_id"], dv.sample_id), "item order differs from I-0"
    res = dict(date=__import__("time").strftime("%Y-%m-%d %H:%M"), best_epochs=[h.best_epoch for h in hs])
    md = []
    for name, sp, new, old in (("validation", va, S["val"], z0["val_scores"]), ("dev_x", dv, S["dev"], z0["dev_scores"])):
        d, bn, bo = B.paired_bootstrap(sp.y, new, old, sp.groups, "auc", n_boot=B.N_BOOT)
        res[name] = dict(new=bn.as_dict(), old=bo.as_dict(), diff=d.as_dict())
    # calibration of the new head (temperature fitted on validation, seed-wise)
    ece = {"validation": [], "dev_x": []}
    for i in range(3):
        T = C.fit_temperature(C.logit(S["val"][i]), va.y).temperature
        ece["validation"].append((M.ece(va.y, S["val"][i]), M.ece(va.y, C.sigmoid(C.logit(S["val"][i]) / T))))
        ece["dev_x"].append((M.ece(dv.y, S["dev"][i]), M.ece(dv.y, C.sigmoid(C.logit(S["dev"][i]) / T))))
    res["ece_before_after"] = {k: np.mean(v, axis=0).tolist() for k, v in ece.items()}
    # manipulation check on the preprocessed signals
    chk = {}
    for nm, (_, manifest, split_csv, split) in zip(("asvspoof_train", "asvspoof_dev", "itw_dev_x"), extract_audio.JOBS):
        recs = L.select_records(manifest, split_csv, split, modality="audio")
        with mp.Pool(8) as pool:
            X = np.array(pool.map(feats_of, [str(Path("data") / r.path) for r in recs], chunksize=64))
        y, g = np.array([r.label for r in recs]), np.array([r.group_id for r in recs])
        chk[nm] = {n: (lambda b: dict(auc=b.estimate, low=b.low, high=b.high))(B.cluster_bootstrap(y, X[:, k][None], g, "auc", n_boot=B.N_BOOT)) for k, n in enumerate(NAMES)}
    res["manipulation_check"] = chk
    dev_chk = chk["asvspoof_dev"]
    res["manipulation_ok"] = bool(all(dev_chk[n]["low"] <= 0.5 <= dev_chk[n]["high"] for n in ("leading_silence_s", "rms", "duration_s")))
    d_dev, d_val = res["dev_x"]["diff"], res["validation"]["diff"]
    val_drop_ok = d_val["estimate"] >= -0.02
    if not res["manipulation_ok"]:
        verdict = "NOT TESTED (the manipulation check failed: a trivial feature still separates the classes on ASVspoof dev)"
    elif d_dev["low"] > 0 and val_drop_ok:
        verdict = "SUPPORTED"
    else:
        verdict = "NOT SUPPORTED (dev_x paired interval includes zero or is below zero, or validation AUC fell by more than 0.02)"
    res["verdict"] = verdict
    md.append("| split | new (trimmed, normalised) | I-0 probe | new minus I-0 |")
    md.append("|---|---|---|---|")
    for name in ("validation", "dev_x"):
        o = res[name]
        md.append(f"| {name} | {o['new']['estimate']:.4f} [{o['new']['low']:.4f}, {o['new']['high']:.4f}] | {o['old']['estimate']:.4f} [{o['old']['low']:.4f}, {o['old']['high']:.4f}] | {o['diff']['estimate']:+.4f} [{o['diff']['low']:+.4f}, {o['diff']['high']:+.4f}] |")
    md.append("")
    md.append("Manipulation check, AUC of the single feature on the preprocessed signal (0.5 = no information; M-004 before: ASVspoof dev leading silence 0.375, RMS 0.594, duration 0.467, repeat-padded fraction 0.543):")
    md.append("")
    md.append("| feature | ASVspoof train | ASVspoof dev | In-the-Wild dev_x |")
    md.append("|---|---|---|---|")
    for n in NAMES:
        md.append(f"| {n} | " + " | ".join(f"{chk[k][n]['auc']:.3f} [{chk[k][n]['low']:.3f}, {chk[k][n]['high']:.3f}]" for k in ("asvspoof_train", "asvspoof_dev", "itw_dev_x")) + " |")
    md.append("")
    md.append(f"ECE before / after temperature scaling (fitted on validation): validation {res['ece_before_after']['validation'][0]:.4f} / {res['ece_before_after']['validation'][1]:.4f}, dev_x {res['ece_before_after']['dev_x'][0]:.4f} / {res['ece_before_after']['dev_x'][1]:.4f} (I-0: 0.0883 / 0.0078 and 0.3293 / 0.4052).")
    md.append("")
    md.append(f"Manipulation check {'passed' if res['manipulation_ok'] else 'FAILED'} (the intervals of leading silence, RMS and duration on ASVspoof dev include 0.5).")
    gain = d_dev["estimate"]
    md.append(f"Prediction check: dev_x gain +0.05 to +0.15, found {gain:+.4f} ({'inside' if 0.05 <= gain <= 0.15 else 'larger than' if gain > 0.15 else 'smaller than'} the range); validation change at most -0.01, found {d_val['estimate']:+.4f}.")
    md.append("")
    md.append(f"**VERDICT (mechanical, exploratory on dev_x, D-041): {verdict}.**")
    block = "\n".join(md)
    (OUT / "ha1.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "ha1.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new = f"- Result (generated by scripts/i2/run_ha1.py from data/_results/I-2, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new + t[j:]
        else:
            assert "- Result: (written by script after the run, E-007)" in t
            t = t.replace("- Result: (written by script after the run, E-007)", new)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
