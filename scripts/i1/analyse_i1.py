"""I-1 analysis (E-005): stage tables, selection, the mechanical verdict C1 to C3, the diagnostic battery on the winner (CPU only).

    PYTHONPATH=src .venv/Scripts/python.exe scripts/i1/analyse_i1.py [--write]

Reads data/_results/I-1/ (runs, selection.json) and the I-0 and sweep score files; train, validation and dev_x only. Writes
data/_results/I-1/result.md and analysis.json, contact sheets of the worst errors to data/_results/I-1/worst/ (local only, dataset licences),
and with --write replaces the "Result" line of the E-005 entry in docs/EXPERIMENTS.md (between markers, rerunnable).
Verdict (written in E-005 before the run): C1 validation gain lower bound above 0, C2 training-subset AUC at least 0.90, C3 dev_x gain lower bound above 0.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "mvp"))
import battery as BAT  # noqa: E402

from dfd.eval import bootstrap as B  # noqa: E402
from dfd.eval import calibration as C  # noqa: E402
from dfd.eval import metrics as M  # noqa: E402
from dfd.sweep import heads  # noqa: E402
from dfd.sweep.rank import load_split  # noqa: E402
from dfd.sweep.tasks import TASKS  # noqa: E402

OUT = Path("data/_results/I-1")
I0 = Path("data/_results/I-0/T-V/scores.npz")
SWEEP = Path("data/_results/T-V/scores.npz")
CANDS = ["IMG-07", "IMG-17", "IMG-08"]
LRS = [1e-5, 3e-5, 1e-4]
MARK_B, MARK_E = "<!-- E-005 RESULT begin (generated by scripts/i1/analyse_i1.py) -->", "<!-- E-005 RESULT end -->"
L: list[str] = []


def md(s=""):
    L.append(s)


def f4(x):
    return "n/a" if x is None or x != x else f"{x:.4f}"


def ci(b):
    return f"{b.estimate:.4f} [{b.low:.4f}, {b.high:.4f}]"


def load_run(c, lr, seed):
    d = OUT / f"{c}_lr{lr:g}_s{seed}"
    r = json.loads((d / "result.json").read_text())
    z = np.load(d / "scores.npz", allow_pickle=True) if (d / "scores.npz").is_file() else None
    return r, z


def probe_scores(cand, i0, sw, ft_val_y, ft_dev_sid):
    """Three-seed linear-probe clip scores of the same encoder on validation, dev_x and the strided training subset (same clips, same order)."""
    if cand == "IMG-07":
        tr = i0["train_scores"][:, ::4]
        return i0["val_scores"], i0["dev_scores"], tr
    assert np.array_equal(sw["val_y"], ft_val_y), "validation order differs"
    assert np.array_equal(sw["sample_id"], ft_dev_sid), "dev_x order differs"
    task = TASKS["T-V"]
    trn, _ = load_split(cand, task, task.train)
    va, _ = load_split(cand, task, task.val)
    hs = [heads.train_head(trn, va, s) for s in (0, 1, 2)]
    tr = np.array([heads.clip_scores(h.prob_rows(trn.X), trn.clip_of, trn.y.size) for h in hs])[:, ::4]
    return sw[f"val_{cand}"], sw[f"dev_{cand}"], tr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    sel = json.loads((OUT / "selection.json").read_text())
    W, lrW = sel["winner"], sel["winner_lr"]
    i0, sw = np.load(I0, allow_pickle=True), np.load(SWEEP, allow_pickle=True)
    res = {}

    md("#### Stage 1 (seed 0): every run")
    md()
    md("| encoder | learning rate | status | validation AUC | dev_x AUC | training-subset AUC (900 clips) | training s | wall s | peak VRAM GiB | instability events | non-finite losses |")
    md("|---|---|---|---|---|---|---|---|---|---|---|")
    sens = {}
    for c in CANDS:
        v, d = [], []
        for lr in LRS:
            r, _ = load_run(c, lr, 0)
            md(f"| {c} | {lr:g} | {r.get('status')} | {f4(r.get('val_auc'))} | {f4(r.get('devx_auc'))} | {f4(r.get('train_subset_auc'))} | {r.get('train_seconds')} | {r.get('wall_seconds')} | {r.get('peak_vram_gb')} | {r.get('instability_events')} | {r.get('nonfinite_losses')} |")
            if r.get("val_auc") is not None and r.get("status") == "ok":
                v.append(r["val_auc"])
                d.append(r["devx_auc"])
        sens[c] = dict(val=(max(v) - min(v)) if v else None, dev=(max(d) - min(d)) if d else None)
    md()
    md("Learning-rate sensitivity (largest minus smallest AUC over the three rates): " + "; ".join(f"{c} validation {f4(s['val'])}, dev_x {f4(s['dev'])}" for c, s in sens.items()) + ".")
    md()
    md("#### Selection (validation only, D-036 rule on validation clips)")
    md()
    md(f"Best learning rate per encoder: {', '.join(f'{c} {lr:g}' for c, lr in sel['best_lr'].items())}. Leader {sel['leader']}; tie set (cheapest first) {', '.join(sel['tie_set'])}; winner {W} at learning rate {lrW:g} "
       f"({'decided by cost inside a tie set' if sel['cost_decided'] else 'the leader alone'}). Validation AUC of the best-rate runs: "
       + "; ".join(f"{c} {v['estimate']:.4f} [{v['low']:.4f}, {v['high']:.4f}]" for c, v in sel["val_auc"].items())
       + ". Paired difference to the leader: " + "; ".join(f"{c} {v['estimate']:.4f} [{v['low']:.4f}, {v['high']:.4f}]" for c, v in sel["diffs_vs_leader"].items()) + ".")
    md()

    # ---- stage 2 and the verdict
    runs = [load_run(W, lrW, s) for s in (0, 1, 2)]
    bad = [r["name"] for r, _ in runs if r.get("status") != "ok"]
    md(f"#### Winner {W}, learning rate {lrW:g}: seeds 0, 1, 2")
    md()
    md("| seed | status | validation AUC | dev_x AUC | training-subset AUC | training s | wall s | peak VRAM GiB | instability events |")
    md("|---|---|---|---|---|---|---|---|---|")
    for r, _ in runs:
        md(f"| {r['seed']} | {r.get('status')} | {f4(r.get('val_auc'))} | {f4(r.get('devx_auc'))} | {f4(r.get('train_subset_auc'))} | {r.get('train_seconds')} | {r.get('wall_seconds')} | {r.get('peak_vram_gb')} | {r.get('instability_events')} |")
    md()
    if bad:
        md(f"VERDICT: NOT EVALUATED (a run of the winner did not finish: {', '.join(bad)}).")
        res["verdict"] = "NOT EVALUATED"
    else:
        zs = [z for _, z in runs]
        vy, vg = zs[0]["val_y"], zs[0]["val_group"]
        dy, dg, dsid = zs[0]["dev_y"], zs[0]["dev_group"], zs[0]["dev_sample_id"]
        ty = zs[0]["trsub_y"]
        for z in zs[1:]:
            assert np.array_equal(z["val_y"], vy) and np.array_equal(z["dev_sample_id"], dsid)
        ftv, ftd, ftt = (np.array([z[f"{k}_scores"] for z in zs]) for k in ("val", "dev", "trsub"))
        pv, pd_, pt = probe_scores(W, i0, sw, vy, dsid)
        tg = i0["train_group"][::4]
        assert np.array_equal(i0["train_y"][::4], ty), "training subset order differs"
        out = {}
        for name, y, g, ft, pr in (("validation", vy, vg, ftv, pv), ("dev_x", dy, dg, ftd, pd_), ("training subset", ty, tg, ftt, pt)):
            d, bf, bp = B.paired_bootstrap(y, ft, pr, g, "auc", n_boot=B.N_BOOT)
            out[name] = dict(ft=bf.as_dict(), probe=bp.as_dict(), diff=d.as_dict())
        res["paired"] = out
        c1 = out["validation"]["diff"]["low"] > 0
        c2 = out["training subset"]["ft"]["estimate"] >= 0.90
        c3 = out["dev_x"]["diff"]["low"] > 0
        if c1 and c2 and c3:
            verdict = "SUPPORTED"
        elif c1 and c3 and not c2:
            verdict = "PARTIAL (C1 and C3 hold, C2 fails)"
        elif c1 and not c3:
            verdict = "NOT SUPPORTED, failure line of I-1 (validation rises, the dev_x interval includes zero or is below zero: capacity went into source-specific cues)"
        else:
            verdict = "NOT SUPPORTED, bias diagnosis rejected (C1 fails)"
        res.update(verdict=verdict, c1=bool(c1), c2=bool(c2), c3=bool(c3))
        md("| split | fine-tuned (3 seeds) | linear probe of the same encoder (3 seeds) | fine-tuned minus probe |")
        md("|---|---|---|---|")
        for name in ("validation", "dev_x", "training subset"):
            o = out[name]
            md(f"| {name} | {o['ft']['estimate']:.4f} [{o['ft']['low']:.4f}, {o['ft']['high']:.4f}] | {o['probe']['estimate']:.4f} [{o['probe']['low']:.4f}, {o['probe']['high']:.4f}] | {o['diff']['estimate']:+.4f} [{o['diff']['low']:+.4f}, {o['diff']['high']:+.4f}] |")
        md()
        md(f"Criteria (E-005): C1 validation gain lower bound above 0: {'met' if c1 else 'not met'} ({out['validation']['diff']['low']:+.4f}). C2 training-subset AUC at least 0.90: {'met' if c2 else 'not met'} ({out['training subset']['ft']['estimate']:.4f}). C3 dev_x gain lower bound above 0: {'met' if c3 else 'not met'} ({out['dev_x']['diff']['low']:+.4f}).")
        md()
        md(f"**VERDICT (mechanical, exploratory on dev_x, D-041): {verdict}.**")
        pv_gain, pd_gain = out["validation"]["diff"]["estimate"], out["dev_x"]["diff"]["estimate"]
        md()
        md(f"Prediction check (written before the run): validation gain +0.02 to +0.05, found {pv_gain:+.4f} ({'inside' if 0.02 <= pv_gain <= 0.05 else 'larger than' if pv_gain > 0.05 else 'smaller than'} the range); dev_x between slightly negative and +0.03, found {pd_gain:+.4f} ({'inside' if -0.03 <= pd_gain <= 0.03 else 'larger than' if pd_gain > 0.03 else 'below'} the range); training-subset AUC at least 0.90: {out['training subset']['ft']['estimate']:.4f}.")
        md()

        # ---- battery on the winner (seed 0 run for the per-clip views, the 3 seeds for the intervals)
        md("#### Diagnostic battery on the fine-tuned winner (exploratory; train, validation and dev_x only)")
        md()
        z0 = zs[0]
        man = BAT.load_manifest(["ffpp", "celebdf_v2"])
        BAT.L.clear()
        md("Item 1, validation, real against each manipulation method (3 seeds):")
        md()
        BAT.per_method(z0["val_sample_id"], vy, ftv, vg, man, "method", "method")
        L.extend(BAT.L)
        md("Items 2, 3 and 8: gaps and seed variance (training subset 900 clips):")
        md()
        md("| split | AUC [95% interval] | seed sd | interval half-width |")
        md("|---|---|---|---|")
        for name, y, g, ft in (("training subset", ty, tg, ftt), ("validation", vy, vg, ftv), ("dev_x", dy, dg, ftd)):
            b = B.cluster_bootstrap(y, ft, g, "auc", n_boot=B.N_BOOT)
            md(f"| {name} | {ci(b)} | {f4(b.seed_sd)} | {(b.high - b.low) / 2:.4f} |")
        gap_tv = out["training subset"]["ft"]["estimate"] - out["validation"]["ft"]["estimate"]
        gap_vd = out["validation"]["ft"]["estimate"] - out["dev_x"]["ft"]["estimate"]
        md()
        md(f"Training-subset minus validation AUC: {gap_tv:+.4f}. Validation minus dev_x AUC: {gap_vd:+.4f} (I-0: +0.1052).")
        res.update(gap_train_val=float(gap_tv), gap_val_dev=float(gap_vd))
        md()
        md("Item 4, calibration (15 equal-width bins; temperature fitted on the validation split of each seed; ECE before / after, Brier before / after):")
        md()
        md("| split | ECE before / after | Brier before / after | temperatures (seeds 0, 1, 2) | balanced accuracy at the validation threshold |")
        md("|---|---|---|---|---|")
        cal = {"validation": [], "dev_x": []}
        temps, bas = [], {"validation": [], "dev_x": []}
        for i in range(3):
            T = C.fit_temperature(C.logit(ftv[i]), vy).temperature
            temps.append(float(T))
            pvc, pdc = C.sigmoid(C.logit(ftv[i]) / T), C.sigmoid(C.logit(ftd[i]) / T)
            from dfd.eval.threshold import choose_threshold_max_balanced_accuracy as thr_fn
            thr = thr_fn(vy, pvc).threshold
            cal["validation"].append((M.ece(vy, ftv[i]), M.ece(vy, pvc), M.brier(vy, ftv[i]), M.brier(vy, pvc)))
            cal["dev_x"].append((M.ece(dy, ftd[i]), M.ece(dy, pdc), M.brier(dy, ftd[i]), M.brier(dy, pdc)))
            bas["validation"].append(M.balanced_accuracy(vy, pvc, thr))
            bas["dev_x"].append(M.balanced_accuracy(dy, pdc, thr))
        for k in cal:
            m = np.mean(cal[k], axis=0)
            md(f"| {k} | {m[0]:.4f} / {m[1]:.4f} | {m[2]:.4f} / {m[3]:.4f} | {', '.join(f'{t:.3f}' for t in temps)} | {np.mean(bas[k]):.3f} |")
        res.update(ece=dict(validation=np.mean(cal["validation"], axis=0).tolist(), dev_x=np.mean(cal["dev_x"], axis=0).tolist()), temperatures=temps)
        md()
        md("Item 5, quantiles of the seed-mean clip score (not calibrated), 10 / 50 / 90 percent:")
        md()
        md("| split | real | fake |")
        md("|---|---|---|")
        for nm, y, s in (("validation", vy, ftv.mean(0)), ("dev_x", dy, ftd.mean(0))):
            q = lambda m: " / ".join(f"{v:.3f}" for v in np.quantile(s[m], [0.1, 0.5, 0.9]))  # noqa: E731
            md(f"| {nm} | {q(y == 0)} | {q(y == 1)} |")
        md()
        md("Item 6, aggregation and face statistics (seed 0 run):")
        md()
        fs = json.loads(Path("data/_results/I-0/T-V/face_stats.json").read_text())
        md("| split | frame-level AUC | clip mean (shipped rule) | clip median | clip top-3 mean | clip max |")
        md("|---|---|---|---|---|---|")
        agg = {}
        for nm, key, y, g in (("validation", "val", vy, vg), ("dev_x", "dev", dy, dg)):
            p, co = z0[f"{key}_frame_p"].astype(np.float32), z0[f"{key}_frame_clip"]
            n = len(y)
            yf, gf = y[co], g[co]
            row = [BAT.fmt(BAT.auc_ci(yf, p[None, :], gf))]
            per = [[] for _ in range(n)]
            for pi, ci_ in zip(p, co):
                per[ci_].append(pi)
            for fn in (np.mean, np.median, lambda v: float(np.mean(sorted(v)[-3:])), np.max):
                s = np.array([fn(v) if v else np.nan for v in per])
                ok = ~np.isnan(s)
                row.append(BAT.fmt(BAT.auc_ci(y[ok], s[None, ok], g[ok])))
            md(f"| {nm} | " + " | ".join(row) + " |")
            agg[nm] = row
        res["aggregation"] = agg
        md()
        md("| split | faces in three sampled frames | clips | real | fake | AUC [95% interval] |")
        md("|---|---|---|---|---|---|")
        for nm, key, y, g, sid, S in (("validation", "val", vy, vg, z0["val_sample_id"], ftv), ("dev_x", "dev", dy, dg, dsid, ftd)):
            nf = np.array([fs.get(str(s), {}).get("n_faces", -1) for s in sid])
            for lab, k in (("1", nf == 1), ("2 or more", nf >= 2)):
                if k.sum() >= 10 and len(np.unique(y[k])) == 2:
                    md(f"| {nm} | {lab} | {int(k.sum())} | {int((y[k] == 0).sum())} | {int((y[k] == 1).sum())} | {BAT.fmt(BAT.auc_ci(y[k], S[:, k], g[k]))} |")
        md()
        md("Item 7, the 20 worst errors on dev_x (10 false alarms, 10 misses), seed-mean score:")
        md()
        s = ftd.mean(0)
        order_fa = np.argsort(-np.where(dy == 0, s, -1))[:10]
        order_ms = np.argsort(np.where(dy == 1, s, 2))[:10]
        md("| kind | sample | group | score |")
        md("|---|---|---|---|")
        for kind, idxs in (("false alarm", order_fa), ("miss", order_ms)):
            for i in idxs:
                md(f"| {kind} | {dsid[i]} | {dg[i]} | {s[i]:.3f} |")
        pg = {}
        for i in list(order_fa) + list(order_ms):
            pg[dg[i]] = pg.get(dg[i], 0) + 1
        md()
        md("Worst errors per group: " + ", ".join(f"{k} {v}" for k, v in sorted(pg.items(), key=lambda kv: -kv[1])) + ".")
        res["worst_groups"] = pg
        # contact sheets (local only)
        try:
            import csv
            from dfd.prep.pipeline import folder_name
            crops = "data/_crops/celebdf_v2_yunet_n16"
            def mid(sid_):
                with open(Path(crops) / folder_name(str(sid_)) / "index.csv", encoding="utf-8", newline="") as fh:
                    rows = [r for r in csv.DictReader(fh) if r["detected"] == "1" and r["crop_path"]]
                return str(Path(crops) / rows[len(rows) // 2]["crop_path"])
            for nm, idxs in (("false_alarms", order_fa), ("misses", order_ms)):
                BAT.contact_sheet([mid(dsid[i]) for i in idxs], [s[i] for i in idxs], [int(dy[i]) for i in idxs], OUT / "worst" / f"{nm}.jpg")
        except Exception as e:  # recorded, not hidden
            md(f"(contact sheets not made: {type(e).__name__}: {e})")
    block = "\n".join(L)
    (OUT / "result.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "analysis.json").write_text(json.dumps(res, indent=1, default=float))
    print(block[:3000])
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new = f"- Result (generated by scripts/i1/analyse_i1.py from data/_results/I-1, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new + t[j:]
        else:
            assert "- Result: (written by script after the run)" in t
            t = t.replace("- Result: (written by script after the run)", new)
        p.write_text(t, encoding="utf-8")
        print("written to docs/EXPERIMENTS.md")


if __name__ == "__main__":
    main()
