"""E-013 analysis: Xception baseline against the E-005 winner (IMG-17) and the I-0 probe, on validation and dev_x.

    PYTHONPATH=src .venv/Scripts/python.exe scripts/baseline/analyse_baseline.py [--write]
    PYTHONPATH=src .venv/Scripts/python.exe scripts/baseline/analyse_baseline.py --b [--write]    # E-013b: the grid with 3e-4 (D-062 a)
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from dfd.eval import bootstrap as B

OUT = Path("data/_results/baseline")
I1 = Path("data/_results/I-1")
MARK_B, MARK_E = "<!-- E-013 RESULT begin (generated by scripts/baseline/analyse_baseline.py) -->", "<!-- E-013 RESULT end -->"
MARK_BB, MARK_BE = "<!-- E-013b RESULT begin (generated by scripts/baseline/analyse_baseline.py --b) -->", "<!-- E-013b RESULT end -->"


def fmt(b):
    return f"{b['estimate']:.4f} [{b['low']:.4f}, {b['high']:.4f}]"


def dfmt(b):
    return f"{b['estimate']:+.4f} [{b['low']:+.4f}, {b['high']:+.4f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--b", action="store_true", help="E-013b: use selection_b.json (grid extended to 3e-4), write e013b.* and the E-013b block")
    a = ap.parse_args()
    sel = json.loads((OUT / ("selection_b.json" if a.b else "selection.json")).read_text())
    lr = sel["best_lr"]
    base = [np.load(OUT / f"IMG-04_lr{lr:g}_s{s}" / "scores.npz", allow_pickle=True) for s in range(3)]
    ours = [np.load(I1 / f"IMG-17_lr1e-05_s{s}" / "scores.npz", allow_pickle=True) for s in range(3)]
    i0 = np.load("data/_results/I-0/T-V/scores.npz", allow_pickle=True)
    res = dict(best_lr=lr, stage1={k: v for k, v in sel["val_auc"].items()})
    md = [f"Selected learning rate (validation AUC only): {lr:g}; stage 1 validation AUC by rate: " + ", ".join(f"{k} {v:.4f}" for k, v in sel["val_auc"].items() if v is not None) + ".", "",
          "| split | Xception baseline (3 seeds) | IMG-17 fine-tuned (E-005, 3 seeds) | IMG-17 minus Xception, paired | I-0 probe (IMG-07) | Xception minus I-0 |", "|---|---|---|---|---|---|"]
    for name, key in (("validation", "val"), ("dev_x", "dev")):
        y, g = base[0][f"{key}_y"], base[0][f"{key}_group"]
        for s in range(1, 3):
            assert np.array_equal(base[s][f"{key}_sample_id"], base[0][f"{key}_sample_id"]) and np.array_equal(ours[s][f"{key}_sample_id"], base[0][f"{key}_sample_id"])
        sb = np.array([z[f"{key}_scores"] for z in base])
        so = np.array([z[f"{key}_scores"] for z in ours])
        si = i0[f"{key}_scores"]
        assert np.array_equal(i0[f"{key}_sample_id"], base[0][f"{key}_sample_id"])
        d, bo, bb = B.paired_bootstrap(y, so, sb, g, "auc", n_boot=B.N_BOOT)
        d2, _, bi = B.paired_bootstrap(y, sb, si, g, "auc", n_boot=B.N_BOOT)
        sd = float(np.std([B.cluster_bootstrap(y, sb[k], g, "auc", n_boot=10).estimate for k in range(3)], ddof=1))
        res[name] = dict(baseline=bb.as_dict(), ours=bo.as_dict(), diff_ours_minus_baseline=d.as_dict(), i0=bi.as_dict(), diff_baseline_minus_i0=d2.as_dict(), baseline_seed_sd=sd)
        md.append(f"| {name} | {fmt(res[name]['baseline'])} (seed sd {sd:.4f}) | {fmt(res[name]['ours'])} | {dfmt(res[name]['diff_ours_minus_baseline'])} | {fmt(res[name]['i0'])} | {dfmt(res[name]['diff_baseline_minus_i0'])} |")
    if a.b:
        others = [v for k, v in sel["val_auc"].items() if k != "0.0003" and v is not None]
        v3 = sel["val_auc"].get("0.0003")
        picked = v3 is not None and v3 == v3 and v3 > max(others)
        md += ["", f"E-013b selection rule (seed 0 validation AUC of 3e-4 strictly above every other rate): 3e-4 gives {v3:.4f} against a best other of {max(others):.4f}: **{'SELECTED' if picked else 'NOT SELECTED'}** (mechanical, validation only)."]
        res["e013b_selected"] = bool(picked)
        old = [np.load(OUT / f"IMG-04_lr0.0001_s{s}" / "scores.npz", allow_pickle=True) for s in range(3)]
        md += ["", f"Selected rate {lr:g} against the E-013 rate 1e-4 (paired, 3 seeds each, exploratory):", "", "| split | baseline at the selected rate | E-013 baseline (1e-4) | selected minus E-013 |", "|---|---|---|---|"]
        for name, key in (("validation", "val"), ("dev_x", "dev")):
            y, g = base[0][f"{key}_y"], base[0][f"{key}_group"]
            sn = np.array([z[f"{key}_scores"] for z in base])
            so_ = np.array([z[f"{key}_scores"] for z in old])
            d3, b3, b1 = B.paired_bootstrap(y, sn, so_, g, "auc", n_boot=B.N_BOOT)
            res[name]["diff_selected_minus_e013"] = d3.as_dict()
            res[name]["e013_baseline"] = b1.as_dict()
            md.append(f"| {name} | {fmt(b3.as_dict())} | {fmt(b1.as_dict())} | {dfmt(d3.as_dict())} |")
    delta = max(0.01, 2 * max(res["validation"]["baseline_seed_sd"], res["dev_x"]["baseline_seed_sd"]))
    res["delta_d025"] = delta
    dv = res["dev_x"]["diff_ours_minus_baseline"]
    verdict = ("SUPPORTED" if dv["low"] > 0 else "NOT SUPPORTED")
    res["verdict"] = verdict
    label = "E-013b" if a.b else "E-013"
    md += ["", (f"Hypothesis of {label} (IMG-17 fine-tuned is superior to the Xception baseline on dev_x, lower bound of the paired difference above 0): " if not a.b else
                "Context, not a hypothesis of E-013b (the E-013 comparison repeated with the selected baseline: lower bound of IMG-17 minus Xception on dev_x above 0): ") +
           f"**{verdict}** (mechanical, exploratory, D-041). The seed standard deviation of the baseline on each split (above) is the quantity from which delta of D-025 is chosen before the final comparison (D-060). Delta by the rule of D-060 (2 times the larger seed standard deviation, floor 0.01): {delta:.4f}.", ""]
    block = "\n".join(md)
    sfx = "b" if a.b else ""
    (OUT / f"e013{sfx}.md").write_text(block + "\n", encoding="utf-8")
    (OUT / f"e013{sfx}.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        mb, me = (MARK_BB, MARK_BE) if a.b else (MARK_B, MARK_E)
        tag = ' --b' if a.b else ''
        new_txt = f"- Result (generated by scripts/baseline/analyse_baseline.py{tag} from data/_results/baseline, rerunnable):\n{mb}\n\n{block}\n\n{me}"
        if mb in t:
            i, j = t.index(mb), t.index(me) + len(me)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            old = f"- Result: (written by script after the run, {label})"
            assert old in t
            t = t.replace(old, new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
