"""E-013 analysis: Xception baseline against the E-005 winner (IMG-17) and the I-0 probe, on validation and dev_x.

    PYTHONPATH=src .venv/Scripts/python.exe scripts/baseline/analyse_baseline.py [--write]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from dfd.eval import bootstrap as B

OUT = Path("data/_results/baseline")
I1 = Path("data/_results/I-1")
MARK_B, MARK_E = "<!-- E-013 RESULT begin (generated by scripts/baseline/analyse_baseline.py) -->", "<!-- E-013 RESULT end -->"


def fmt(b):
    return f"{b['estimate']:.4f} [{b['low']:.4f}, {b['high']:.4f}]"


def dfmt(b):
    return f"{b['estimate']:+.4f} [{b['low']:+.4f}, {b['high']:+.4f}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    sel = json.loads((OUT / "selection.json").read_text())
    lr = sel["best_lr"]
    base = [np.load(OUT / f"IMG-04_lr{lr:g}_s{s}" / "scores.npz", allow_pickle=True) for s in range(3)]
    ours = [np.load(I1 / f"IMG-17_lr1e-05_s{s}" / "scores.npz", allow_pickle=True) for s in range(3)]
    i0 = np.load("data/_results/I-0/T-V/scores.npz", allow_pickle=True)
    res = dict(best_lr=lr, stage1={k: v for k, v in sel["val_auc"].items()})
    md = [f"Selected learning rate (validation AUC only): {lr:g}; stage 1 validation AUC by rate: " + ", ".join(f"{k} {v:.4f}" for k, v in sel["val_auc"].items() if v is not None) + ".", "",
          "| split | Xception baseline (3 seeds) | IMG-17 fine-tuned (E-005, 3 seeds) | IMG-17 minus Xception, paired | I-0 probe (IMG-07) | Xception minus I-0 |", "|---|---|---|---|---|---|"]
    for name, key in (("validation", "val"), ("dev_x", "dev")):
        y, g = base[0][f"{key}_y"], base[0][f"{key}_group"]
        for s in range(1, 3):
            assert np.array_equal(base[s][f"{key}_sample_id"], base[0][f"{key}_sample_id"]) and np.array_equal(ours[s][f"{key}_sample_id"], base[0][f"{key}_sample_id"])
        sb = np.array([z[f"{key}_scores"] for z in base])
        so = np.array([z[f"{key}_scores"] for z in ours])
        si = i0[f"{key}_scores"]
        assert np.array_equal(i0[f"{key}_sample_id"], base[0][f"{key}_sample_id"])
        d, bo, bb = B.paired_bootstrap(y, so, sb, g, "auc", n_boot=B.N_BOOT)
        d2, _, bi = B.paired_bootstrap(y, sb, si, g, "auc", n_boot=B.N_BOOT)
        sd = float(np.std([B.cluster_bootstrap(y, sb[k], g, "auc", n_boot=10).estimate for k in range(3)], ddof=1))
        res[name] = dict(baseline=bb.as_dict(), ours=bo.as_dict(), diff_ours_minus_baseline=d.as_dict(), i0=bi.as_dict(), diff_baseline_minus_i0=d2.as_dict(), baseline_seed_sd=sd)
        md.append(f"| {name} | {fmt(res[name]['baseline'])} (seed sd {sd:.4f}) | {fmt(res[name]['ours'])} | {dfmt(res[name]['diff_ours_minus_baseline'])} | {fmt(res[name]['i0'])} | {dfmt(res[name]['diff_baseline_minus_i0'])} |")
    delta = max(0.01, 2 * max(res["validation"]["baseline_seed_sd"], res["dev_x"]["baseline_seed_sd"]))
    res["delta_d025"] = delta
    dv = res["dev_x"]["diff_ours_minus_baseline"]
    verdict = ("SUPPORTED" if dv["low"] > 0 else "NOT SUPPORTED")
    res["verdict"] = verdict
    md += ["", "Hypothesis of E-013 (IMG-17 fine-tuned is superior to the Xception baseline on dev_x, lower bound of the paired difference above 0): "
           f"**{verdict}** (mechanical, exploratory, D-041). The seed standard deviation of the baseline on each split (above) is the quantity from which delta of D-025 is chosen before the final comparison (D-060). Delta by the rule of D-060 (2 times the larger seed standard deviation, floor 0.01): {delta:.4f}.", ""]
    block = "\n".join(md)
    (OUT / "e013.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "e013.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/baseline/analyse_baseline.py from data/_results/baseline, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-013)" in t
            t = t.replace("- Result: (written by script after the run, E-013)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
