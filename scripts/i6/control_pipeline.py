"""E-011 post-hoc control (labelled as such): pipeline-controlled AUC on LAV-DF val.

    PYTHONPATH="src;scripts/i6" .venv/Scripts/python.exe scripts/i6/control_pipeline.py [--write]

The real videos of LAV-DF are originals; every fake (including the audio-only fakes, whose frames are untouched) was produced by the dataset's
own pipeline. A head that separates "original" from "produced by the pipeline" scores audio-only fakes high although their video is unmodified.
The control keeps only the produced videos (cells video_fake, audio_fake, both_fake) and asks each head for its own modality label:
visual head: modify_video within produced videos; audio head: modify_audio within produced videos. Same scores as analyse_e011.py.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

import analyse_i6 as A6
from dfd.eval import bootstrap as B
from dfd.eval import calibration as C

OUT = Path("data/_results/I-6")
logit, fmt = A6.logit, A6.fmt


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    meta = {s: np.load(OUT / f"scores_{s}.npz", allow_pickle=True) for s in ("train", "val")}
    vis = {s: np.array([np.load(OUT / f"visual_lavdf_s{k}.npz", allow_pickle=True)[f"{s}_p"] for k in range(3)]) for s in ("train", "val")}
    aud = np.load(OUT / "audio_lavdf.npz", allow_pickle=True)
    pa = {s: aud[f"{s}_p"] for s in ("train", "val")}
    Tv = [C.fit_temperature(logit(vis["train"][k]), meta["train"]["y_video"]).temperature for k in range(3)]
    Ta = [C.fit_temperature(np.mean([logit(pa["train"][m, k]) for m in range(3)], axis=0), meta["train"]["y_audio"]).temperature for k in range(3)]
    vv = np.mean([logit(vis["val"][k]) / Tv[k] for k in range(3)], axis=0)
    av = np.mean([np.mean([logit(pa["val"][m, k]) for m in range(3)], axis=0) / Ta[k] for k in range(3)], axis=0)
    v = meta["val"]
    prod = v["cell"] != "real"
    g = v["group"]

    def auc(y, s, m):
        return B.cluster_bootstrap(y[m], s[m], g[m], "auc", n_boot=B.N_BOOT).as_dict()
    res = dict(n_produced=int(prod.sum()),
               visual_modify_video_within_produced=auc(v["y_video"], vv, prod), audio_modify_audio_within_produced=auc(v["y_audio"], av, prod),
               visual_modify_audio_within_produced=auc(v["y_audio"], vv, prod), audio_modify_video_within_produced=auc(v["y_video"], av, prod),
               visual_real_vs_audio_only_fake=auc((v["cell"] == "audio_fake").astype(int), vv, (v["cell"] == "real") | (v["cell"] == "audio_fake")))
    md = ["Post-hoc control (not a pre-declared criterion; scripts/i6/control_pipeline.py): AUC [95% group bootstrap] on LAV-DF val within the produced videos only (cells video_fake, audio_fake, both_fake; the real originals are left out), so that every clip went through the dataset's own pipeline.", "",
          "| score | label asked | AUC within produced videos |", "|---|---|---|",
          f"| visual head | modify_video | {fmt(res['visual_modify_video_within_produced'])} |", f"| audio head | modify_audio | {fmt(res['audio_modify_audio_within_produced'])} |",
          f"| visual head | modify_audio (should be near 0.5) | {fmt(res['visual_modify_audio_within_produced'])} |", f"| audio head | modify_video (should be near 0.5) | {fmt(res['audio_modify_video_within_produced'])} |", "",
          f"Visual head, real originals against audio-only fakes (video unmodified): {fmt(res['visual_real_vs_audio_only_fake'])}."]
    block = "\n".join(md)
    (OUT / "e011_control.json").write_text(json.dumps(res, indent=1, default=float))
    (OUT / "e011_control.md").write_text(block + "\n", encoding="utf-8")
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        mb, me = "<!-- E-011 CONTROL begin (generated by scripts/i6/control_pipeline.py) -->", "<!-- E-011 CONTROL end -->"
        new = f"- Post-hoc control of E-011 (written after the result above, labelled exploratory; it does not change the mechanical verdict):\n{mb}\n\n{block}\n\n{me}"
        if mb in t:
            i, j = t.index(mb), t.index(me) + len(me)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new + t[j:]
        else:
            anchor = "<!-- E-011 RESULT end -->"
            t = t.replace(anchor, anchor + "\n" + new, 1)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
