"""E-010 analysis: pre-check of the frozen heads on LAV-DF `val` and, if both pass, late fusion (D-057).

    PYTHONPATH=src .venv/Scripts/python.exe scripts/i6/analyse_i6.py [--write]

Needs data/_results/I-6/scores_train.npz and scores_val.npz (scripts/i6/score_lavdf.py). No test split is read.
Audio side: the E-009 ensemble (AU-8, AU-4, AU-6) if the E-009 verdict is SUPPORTED, else the AU-8 head alone (the branch written in D-057).
Temperatures: visual from FF++ val (E-005 score files), audio from ASVspoof dev (the heads on the E-007 features); also refitted on LAV-DF train.
Fusion rules: (a) sum of the calibrated log-odds; (b) logistic regression on the two log-odds fitted on LAV-DF train (Newton, no penalty).
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import numpy as np

from dfd.eval import bootstrap as B
from dfd.eval import calibration as C
from dfd.eval import metrics as M

OUT = Path("data/_results/I-6")
MARK_B, MARK_E = "<!-- E-010 RESULT begin (generated by scripts/i6/analyse_i6.py) -->", "<!-- E-010 RESULT end -->"
SEEDS = (0, 1, 2)


def fmt(b):
    return f"{b['estimate']:.4f} [{b['low']:.4f}, {b['high']:.4f}]"


def dfmt(b):
    return f"{b['estimate']:+.4f} [{b['low']:+.4f}, {b['high']:+.4f}]"


def logit(p):
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return np.log(p / (1 - p))


def fit_lr(X, y, iters=50):
    """Logistic regression without penalty by Newton steps (3 parameters); returns [w0, w1, w2]."""
    A = np.c_[np.ones(len(X)), X]
    w = np.zeros(A.shape[1])
    for _ in range(iters):
        p = 1 / (1 + np.exp(-A @ w))
        g = A.T @ (p - y)
        H = (A * (p * (1 - p))[:, None]).T @ A + 1e-8 * np.eye(A.shape[1])
        step = np.linalg.solve(H, g)
        w -= step
        if np.abs(step).max() < 1e-8:
            break
    return w


def source_temperatures(members):
    """Temperatures on the source-domain validation splits, seed by seed."""
    Tv = []
    for s in SEEDS:
        z = np.load(f"data/_results/I-1/IMG-17_lr1e-05_s{s}/scores.npz", allow_pickle=True)
        Tv.append(C.fit_temperature(C.logit(np.clip(z["val_scores"], 1e-6, 1 - 1e-6)), z["val_y"].astype(int)).temperature)
    Ta, aud_val = [], {}
    for c in members:
        f = np.load(f"data/_features_trimnorm/{c}/T-A/asvspoof_dev.npz")
        aud_val[c] = (f["feats"].astype(np.float32), f["label"].astype(int))
    y = aud_val[members[0]][1]
    for s in SEEDS:
        zs = []
        for c in members:
            h = np.load(OUT.parent / "I-4" / f"head_{c}_s{s}.npz")
            zs.append(((aud_val[c][0] - h["mean"]) / h["std"]) @ h["w"] + float(h["b"]))
        Ta.append(C.fit_temperature(np.mean(zs, axis=0), y).temperature)
    return Tv, Ta


def modality_logits(sc, members_idx, Tv, Ta):
    vis = np.nanmean([logit(sc["vis_p"][k]) / Tv[k] for k in range(3)], axis=0)       # NaN where no face frame was found
    aud = np.mean([np.mean([logit(sc["aud_p"][m, k]) for m in members_idx], axis=0) / Ta[k] for k in range(3)], axis=0)
    return vis, aud


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    ha3 = json.loads((OUT.parent / "I-4" / "ha3.json").read_text())
    ens_ok = ha3["verdict"].startswith("SUPPORTED")
    all_members = ["AU-8", "AU-4", "AU-6"]
    members = all_members if ens_ok else ["AU-8"]
    midx = [all_members.index(c) for c in members]
    tr, va = np.load(OUT / "scores_train.npz", allow_pickle=True), np.load(OUT / "scores_val.npz", allow_pickle=True)
    assert [str(m) for m in tr["members"]] == all_members
    Tv, Ta = source_temperatures(members)
    res = dict(date=time.strftime("%Y-%m-%d %H:%M"), audio_members=members, e009_verdict=ha3["verdict"], T_visual=Tv, T_audio=Ta, n=dict(train=int(len(tr["y_fused"])), val=int(len(va["y_fused"]))))
    vt, at = modality_logits(tr, midx, Tv, Ta)
    vv, av = modality_logits(va, midx, Tv, Ta)
    res["no_face_clips"] = dict(train=int(np.isnan(vt).sum()), val=int(np.isnan(vv).sum()))
    g, yf, yv, ya = va["group"], va["y_fused"], va["y_video"], va["y_audio"]
    ok = ~np.isnan(vv)

    def auc(y, s, mask=None):
        m = np.ones(len(y), bool) if mask is None else mask
        return B.cluster_bootstrap(y[m], s[m], g[m], "auc", n_boot=B.N_BOOT).as_dict()
    pre = dict(visual_vs_video=auc(yv, vv, ok), audio_vs_audio=auc(ya, av), visual_vs_fused=auc(yf, vv, ok), audio_vs_fused=auc(yf, av))
    res["precheck"] = pre
    res["visual_pass"] = bool(pre["visual_vs_video"]["low"] > 0.55)
    res["audio_pass"] = bool(pre["audio_vs_audio"]["low"] > 0.55)
    cells = {}
    for cell in ("video_fake", "audio_fake", "both_fake"):
        m = (va["cell"] == cell) | (va["cell"] == "real")
        cells[cell] = dict(visual=auc((va["cell"] == cell).astype(int), vv, m & ok), audio=auc((va["cell"] == cell).astype(int), av, m))
    res["per_cell"] = cells
    # calibration on LAV-DF val: source-domain temperature (already applied) and a temperature refitted on LAV-DF train
    Tv_l = C.fit_temperature(vt[~np.isnan(vt)], tr["y_video"][~np.isnan(vt)]).temperature
    Ta_l = C.fit_temperature(at, tr["y_audio"]).temperature
    res["ece"] = dict(visual_source_T=M.ece(yv[ok], 1 / (1 + np.exp(-vv[ok]))), visual_lavdf_T=M.ece(yv[ok], 1 / (1 + np.exp(-vv[ok] / Tv_l))),
                      audio_source_T=M.ece(ya, 1 / (1 + np.exp(-av))), audio_lavdf_T=M.ece(ya, 1 / (1 + np.exp(-av / Ta_l))), T_lavdf=dict(visual=Tv_l, audio=Ta_l))
    res["corr_logits"] = dict(real=float(np.corrcoef(vv[ok & (yf == 0)], av[ok & (yf == 0)])[0, 1]), fake=float(np.corrcoef(vv[ok & (yf == 1)], av[ok & (yf == 1)])[0, 1]))
    # fusion (computed and reported whatever the pre-check says, but the verdict follows the pre-check)
    vt0, vv0 = np.nan_to_num(vt, nan=0.0), np.nan_to_num(vv, nan=0.0)
    w = fit_lr(np.c_[vt0, at], tr["y_fused"])
    rules = {"sum of log-odds": vv0 + av, "logistic regression": w[0] + w[1] * vv0 + w[2] * av}
    res["lr_weights"] = dict(w0=float(w[0]), w_visual=float(w[1]), w_audio=float(w[2]))
    single = {"visual head": vv0, "audio head": av}
    sauc = {k: auc(yf, v) for k, v in single.items()}
    best_single = max(sauc, key=lambda k: sauc[k]["estimate"])
    fus = {k: auc(yf, v) for k, v in rules.items()}
    best_rule = max(fus, key=lambda k: fus[k]["estimate"])
    d, _, _ = B.paired_bootstrap(yf, rules[best_rule], single[best_single], g, "auc", n_boot=B.N_BOOT)
    res.update(single_fused_label=sauc, fusion_fused_label=fus, best_single=best_single, best_rule=best_rule, diff_best_rule_vs_best_single=d.as_dict())
    res["fusion_other_labels"] = {k: dict(video=auc(yv, v), audio=auc(ya, v)) for k, v in {**rules, **single}.items()}
    if not (res["visual_pass"] and res["audio_pass"]):
        failing = [n for n, ok_ in (("visual", res["visual_pass"]), ("audio", res["audio_pass"])) if not ok_]
        verdict = f"NOT TESTED (pre-check: the {' and '.join(failing)} head is near chance on LAV-DF, lower bound at or below 0.55; no fused result is claimed)"
    elif d.low > 0:
        verdict = "SUPPORTED"
    else:
        verdict = "NOT SUPPORTED (the interval of the best fusion rule minus the better single head includes zero or is below zero)"
    res["verdict"] = verdict
    md = [f"Audio side: {' + '.join(members)} (E-009 verdict: {ha3['verdict'][:40]}). Clips without a visual score: train {res['no_face_clips']['train']}, val {res['no_face_clips']['val']} of 2,000. Temperatures (seeds 0, 1, 2): visual {np.round(Tv, 3).tolist()}, audio {np.round(Ta, 3).tolist()}; refitted on LAV-DF train: visual {Tv_l:.3f}, audio {Ta_l:.3f}.",
          "", "Pre-check on LAV-DF val (frozen heads, no fitting; AUC with 95 percent group bootstrap interval):", "", "| head | against its own modality label | against the fused label |", "|---|---|---|",
          f"| visual (IMG-17, E-005) | {fmt(pre['visual_vs_video'])} | {fmt(pre['visual_vs_fused'])} |", f"| audio ({' + '.join(members)}) | {fmt(pre['audio_vs_audio'])} | {fmt(pre['audio_vs_fused'])} |", "",
          f"Pre-check rule: lower bound above 0.55. Visual: {'pass' if res['visual_pass'] else 'FAIL'}; audio: {'pass' if res['audio_pass'] else 'FAIL'}.", "",
          "Per cell on val (the cell against the real videos), AUC [95%]:", "", "| cell | visual head | audio head |", "|---|---|---|"]
    for cname, v in cells.items():
        md.append(f"| {cname} | {fmt(v['visual'])} | {fmt(v['audio'])} |")
    e = res["ece"]
    md += ["", f"ECE on val against the own modality label, before any LAV-DF fitting (source-domain temperature) and with the temperature refitted on LAV-DF train: visual {e['visual_source_T']:.4f} / {e['visual_lavdf_T']:.4f}, audio {e['audio_source_T']:.4f} / {e['audio_lavdf_T']:.4f}.",
           f"Pearson correlation of the calibrated visual and audio log-odds on val: real clips {res['corr_logits']['real']:.3f}, fake clips {res['corr_logits']['fake']:.3f}.", "",
           "Fusion on val against the fused label (computed for the record; the verdict follows the pre-check). Logistic regression fitted on LAV-DF train: "
           f"intercept {w[0]:+.3f}, visual weight {w[1]:.3f}, audio weight {w[2]:.3f}.", "", "| scores | AUC [95%] fused label | AUC against modify_video | AUC against modify_audio |", "|---|---|---|---|"]
    for k in list(single) + list(rules):
        row = sauc[k] if k in single else fus[k]
        o = res["fusion_other_labels"][k]
        md.append(f"| {k} | {fmt(row)} | {fmt(o['video'])} | {fmt(o['audio'])} |")
    md += ["", f"Best single head by val AUC: {best_single}; best fusion rule by val AUC: {best_rule}; difference (best rule minus best single head, paired group bootstrap): {dfmt(res['diff_best_rule_vs_best_single'])}.", "",
           f"**VERDICT (mechanical, exploratory, D-041): {verdict}.**"]
    block = "\n".join(md)
    (OUT / "e010.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "e010.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/i6/analyse_i6.py from data/_results/I-6, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-010)" in t
            t = t.replace("- Result: (written by script after the run, E-010)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
