"""E-009 (hypothesis H-A3 of D-056): average of the logits of three speech encoders (AU-8, AU-4, AU-6).

    # 1. features of AU-4 and AU-6 (GPU, CPU workers): see the Command line of E-009 in docs/EXPERIMENTS.md
    # 2. heads, combination, paired comparison with the E-008 head of AU-8 (CPU):
    PYTHONPATH=src .venv/Scripts/python.exe scripts/i4/run_ha3.py [--write]

Each member: the pipeline of E-008 (E-007 window, three augmented copies of every training clip, dfd.sweep.heads recipe, seeds 0, 1, 2).
Combination for seed s: mean of the members' logits of the clip probability. Paired group bootstrap (speaker), 2,000 resamples.
Output data/_results/I-4/ha3.json and ha3.md; with --write the "Result" line of E-009 in docs/EXPERIMENTS.md is replaced between markers.
"""
from __future__ import annotations

import argparse
import itertools
import json
import time
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

from dfd.eval import bootstrap as B
from dfd.eval import calibration as C
from dfd.eval import metrics as M
from dfd.sweep import heads, rank, tasks

OUT = Path("data/_results/I-4")
FEATS = Path("data/_features_trimnorm")
AUGROOT = Path("data/_features_aug")
MEMBERS = ["AU-8", "AU-4", "AU-6"]
MARK_B, MARK_E = "<!-- E-009 RESULT begin (generated by scripts/i4/run_ha3.py) -->", "<!-- E-009 RESULT end -->"


def fmt(b):
    return f"{b['estimate']:.4f} [{b['low']:.4f}, {b['high']:.4f}]"


def dfmt(b):
    return f"{b['estimate']:+.4f} [{b['low']:+.4f}, {b['high']:+.4f}]"


def load_aug(cand, name, sample_id):
    z = np.load(AUGROOT / cand / "T-A" / f"{name}.npz", allow_pickle=False)
    assert np.array_equal(z["sample_id"].astype(str), sample_id), f"{cand} {name}: item order differs"
    return z["feats"].astype(np.float32)


def logit(p):
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return np.log(p / (1 - p))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    tasks.FEATURES = FEATS
    task = tasks.TASKS["T-A"]
    t0 = time.time()
    sc = {}          # member -> {"val": [3,N], "dev": [3,N]} clip probabilities
    ids = {}
    for c in MEMBERS:
        tr, _ = rank.load_split(c, task, task.train)
        va, _ = rank.load_split(c, task, task.val)
        dv, _ = rank.load_split(c, task, task.devx)
        n = tr.y.size
        Xa = [load_aug(c, f"asvspoof_train_aug{k}", tr.sample_id) for k in (1, 2, 3)]
        tra = heads.Split(np.concatenate([tr.X] + Xa), np.concatenate([tr.clip_of] + [np.arange(n)] * 3), tr.y, tr.groups, tr.sample_id)
        hs = [heads.train_head(tra, va, s) for s in (0, 1, 2)]
        sc[c] = {k: np.array([heads.clip_scores(h.prob_rows(sp.X), sp.clip_of, sp.y.size) for h in hs]) for k, sp in (("val", va), ("dev", dv))}
        sc[c]["epochs"] = [h.best_epoch for h in hs]
        if not ids:
            ids = dict(val=va, dev=dv)
        else:
            assert np.array_equal(ids["val"].sample_id, va.sample_id) and np.array_equal(ids["dev"].sample_id, dv.sample_id)
        print(c, "heads trained", flush=True)
    va, dv = ids["val"], ids["dev"]
    ens = {k: 1 / (1 + np.exp(-np.mean([logit(sc[c][k]) for c in MEMBERS], axis=0))) for k in ("val", "dev")}
    res = dict(date=time.strftime("%Y-%m-%d %H:%M"), seconds=round(time.time() - t0), epochs={c: sc[c]["epochs"] for c in MEMBERS})
    ha2 = json.loads(Path("data/_results/I-3/ha2.json").read_text())
    for name, sp, k in (("validation", va, "val"), ("dev_x", dv, "dev")):
        res[name] = {}
        d, be, bb = B.paired_bootstrap(sp.y, ens[k], sc["AU-8"][k], sp.groups, "auc", n_boot=B.N_BOOT)
        res[name]["ensemble"] = be.as_dict()
        res[name]["diff_vs_au8"] = d.as_dict()
        res[name]["au8_reproduced"] = [bb.estimate, ha2[name]["new"]["estimate"]]
        for c in MEMBERS:
            res[name][c] = B.cluster_bootstrap(sp.y, sc[c][k], sp.groups, "auc", n_boot=B.N_BOOT).as_dict()
            dm, _, _ = B.paired_bootstrap(sp.y, ens[k], sc[c][k], sp.groups, "auc", n_boot=B.N_BOOT)
            res[name]["diff_vs_" + c] = dm.as_dict()
    res["correlation"] = {k: {f"{p}-{q}": float(np.mean([spearmanr(sc[p][k][s], sc[q][k][s])[0] for s in range(3)])) for p, q in itertools.combinations(MEMBERS, 2)} for k in ("val", "dev")}
    res["correlation_mean"] = {k: float(np.mean(list(v.values()))) for k, v in res["correlation"].items()}
    best_val = max(MEMBERS, key=lambda c: res["validation"][c]["estimate"])    # best single member chosen on validation (rule 3)
    res["best_single_by_validation"] = best_val
    ece = {"validation": [], "dev_x": []}
    for i in range(3):
        T = C.fit_temperature(C.logit(ens["val"][i]), va.y).temperature
        ece["validation"].append((M.ece(va.y, ens["val"][i]), M.ece(va.y, C.sigmoid(C.logit(ens["val"][i]) / T))))
        ece["dev_x"].append((M.ece(dv.y, ens["dev"][i]), M.ece(dv.y, C.sigmoid(C.logit(ens["dev"][i]) / T))))
    res["ece_before_after"] = {k: np.mean(v, axis=0).tolist() for k, v in ece.items()}
    cost = {}
    for c in MEMBERS:
        m = json.loads((FEATS / c / "T-A" / "itw_dev_x.json").read_text())
        cost[c] = dict(items_per_s=m["items_per_s"], params=m["params"])
    res["cost"] = cost
    d_dev, d_val = res["dev_x"]["diff_vs_au8"], res["validation"]["diff_vs_au8"]
    if d_dev["low"] > 0 and d_val["estimate"] >= -0.02:
        verdict = "SUPPORTED"
    else:
        verdict = "NOT SUPPORTED (dev_x paired interval includes zero or is below zero, or validation AUC fell by more than 0.02)"
    res["verdict"] = verdict
    md = ["| scores | validation AUC | dev_x AUC | ensemble minus this, validation | ensemble minus this, dev_x |", "|---|---|---|---|---|"]
    md.append(f"| ensemble of AU-8, AU-4, AU-6 | {fmt(res['validation']['ensemble'])} | {fmt(res['dev_x']['ensemble'])} | | |")
    for c in MEMBERS:
        tag = f"{c} alone" + (" (E-008 head)" if c == "AU-8" else "")
        md.append(f"| {tag} | {fmt(res['validation'][c])} | {fmt(res['dev_x'][c])} | {dfmt(res['validation']['diff_vs_' + c])} | {dfmt(res['dev_x']['diff_vs_' + c])} |")
    md += ["", f"Mean pairwise Spearman correlation of the members' clip scores (mean over the seeds): validation {res['correlation_mean']['val']:.3f}, dev_x {res['correlation_mean']['dev']:.3f}; pairs on dev_x: "
           + ", ".join(f"{k} {v:.3f}" for k, v in res["correlation"]["dev"].items()) + ".",
           f"Best single member by validation AUC: {best_val}. Early-stopping epochs (seeds 0, 1, 2): " + "; ".join(f"{c} {res['epochs'][c]}" for c in MEMBERS) + ".",
           f"The retrained AU-8 head gives validation {res['validation']['au8_reproduced'][0]:.4f} and dev_x {res['dev_x']['au8_reproduced'][0]:.4f} against {res['validation']['au8_reproduced'][1]:.4f} and {res['dev_x']['au8_reproduced'][1]:.4f} logged in E-008.",
           f"ECE before / after temperature scaling (fitted on validation), ensemble: validation {res['ece_before_after']['validation'][0]:.4f} / {res['ece_before_after']['validation'][1]:.4f}, dev_x {res['ece_before_after']['dev_x'][0]:.4f} / {res['ece_before_after']['dev_x'][1]:.4f}.",
           "Extraction speed of the members on In-the-Wild dev_x (items per second, end to end, one run): " + ", ".join(f"{c} {cost[c]['items_per_s']}" for c in MEMBERS) + "; parameters: " + ", ".join(f"{c} {cost[c]['params']:,}" for c in MEMBERS) + ".",
           ""]
    gain = d_dev["estimate"]
    md.append(f"Prediction check: dev_x gain over the AU-8 head +0.02 to +0.06, found {gain:+.4f} ({'inside' if 0.02 <= gain <= 0.06 else 'larger than' if gain > 0.06 else 'smaller than'} the range); validation change at most -0.01, found {d_val['estimate']:+.4f}; mean pairwise correlation on dev_x {res['correlation_mean']['dev']:.3f} ({'below' if res['correlation_mean']['dev'] < 0.8 else 'not below'} 0.8).")
    md += ["", f"**VERDICT (mechanical, exploratory on dev_x, D-041): {verdict}.**"]
    block = "\n".join(md)
    (OUT / "ha3.md").write_text(block + "\n", encoding="utf-8")
    (OUT / "ha3.json").write_text(json.dumps(res, indent=1, default=float))
    print(block)
    if a.write:
        p = Path("docs/EXPERIMENTS.md")
        t = p.read_text(encoding="utf-8")
        new_txt = f"- Result (generated by scripts/i4/run_ha3.py from data/_results/I-4, rerunnable):\n{MARK_B}\n\n{block}\n\n{MARK_E}"
        if MARK_B in t:
            i, j = t.index(MARK_B), t.index(MARK_E) + len(MARK_E)
            t = t[:i].rstrip("\n").rsplit("\n", 1)[0] + "\n" + new_txt + t[j:]
        else:
            assert "- Result: (written by script after the run, E-009)" in t
            t = t.replace("- Result: (written by script after the run, E-009)", new_txt)
        p.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
